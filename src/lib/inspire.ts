const QUEUE_KEY = "momoyu_inspire_category_queue_v3";
const TEXT_QUEUE_KEY = "momoyu_inspire_text_queue_v1";

function shuffleInPlace<T>(arr: T[]) {
  for (let i = arr.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [arr[i], arr[j]] = [arr[j], arr[i]];
  }
  return arr;
}

/** 新一轮：11 组随机打乱；avoidFirst 避免与上一轮最后一组撞车 */
function freshCategoryQueue(avoidFirst?: string) {
  const q = shuffleInPlace([...INSPIRE_CATEGORIES]);
  if (avoidFirst && q.length > 1 && q[0] === avoidFirst) {
    const j = 1 + Math.floor(Math.random() * (q.length - 1));
    [q[0], q[j]] = [q[j], q[0]];
  }
  return q;
}

function readCategoryQueue(): string[] {
  try {
    const raw = localStorage.getItem(QUEUE_KEY);
    if (!raw) return [];
    const parsed = JSON.parse(raw) as unknown;
    if (!Array.isArray(parsed)) return [];
    // 去重并只保留仍存在的组；顺序保留
    const seen = new Set<string>();
    const out: string[] = [];
    for (const c of parsed) {
      if (typeof c !== "string" || !byCategory.has(c) || seen.has(c)) continue;
      seen.add(c);
      out.push(c);
    }
    return out;
  } catch {
    return [];
  }
}

function writeCategoryQueue(queue: string[]) {
  try {
    localStorage.setItem(QUEUE_KEY, JSON.stringify(queue));
  } catch {
    /* ignore */
  }
}

function freshTextQueue(category: string, avoidFirst?: string) {
  const pool = (byCategory.get(category) || []).map((i) => i.text);
  const q = shuffleInPlace([...pool]);
  if (avoidFirst && q.length > 1 && q[0] === avoidFirst) {
    const j = 1 + Math.floor(Math.random() * (q.length - 1));
    [q[0], q[j]] = [q[j], q[0]];
  }
  return q;
}

function readTextQueue(category: string): string[] {
  try {
    const raw = localStorage.getItem(TEXT_QUEUE_KEY);
    if (!raw) return [];
    const parsed = JSON.parse(raw) as unknown;
    if (!parsed || typeof parsed !== "object" || Array.isArray(parsed)) return [];
    const list = (parsed as Record<string, unknown>)[category];
    if (!Array.isArray(list)) return [];
    const valid = new Set((byCategory.get(category) || []).map((i) => i.text));
    const seen = new Set<string>();
    const out: string[] = [];
    for (const t of list) {
      if (typeof t !== "string" || !valid.has(t) || seen.has(t)) continue;
      seen.add(t);
      out.push(t);
    }
    return out;
  } catch {
    return [];
  }
}

function writeTextQueue(category: string, queue: string[]) {
  try {
    const raw = localStorage.getItem(TEXT_QUEUE_KEY);
    const all: Record<string, string[]> =
      raw && raw.startsWith("{") ? (JSON.parse(raw) as Record<string, string[]>) : {};
    if (queue.length) all[category] = queue;
    else delete all[category];
    localStorage.setItem(TEXT_QUEUE_KEY, JSON.stringify(all));
  } catch {
    /* ignore */
  }
}

/** 锁定某一类：该类文案一轮打乱，每条只出一次，抽完开下一轮 */
function pickInspireInCategory(category: string, previousText?: string) {
  let queue = readTextQueue(category);
  if (!queue.length) {
    queue = freshTextQueue(category, previousText);
  }
  const next = queue.shift()!;
  writeTextQueue(
    category,
    queue.length ? queue : freshTextQueue(category, next)
  );
  return next;
}

/**
 * 换一换：
 * - 随机灵感：11 组一轮，组顺序随机，每组本轮只出现一次；组内随机文案
 * - 锁定主题：只在该类约 30 条文案里轮换，一轮每条一次
 */
export function pickInspire(
  previousText?: string,
  theme: InspireThemeId = INSPIRE_THEME_RANDOM
) {
  if (theme !== INSPIRE_THEME_RANDOM && byCategory.has(theme)) {
    return pickInspireInCategory(theme, previousText);
  }

  const prevCategory = previousText
    ? byText.get(previousText)?.category
    : undefined;

  let queue = readCategoryQueue();
  if (!queue.length) {
    queue = freshCategoryQueue(prevCategory);
  }

  const category = queue.shift()!;
  writeCategoryQueue(queue.length ? queue : freshCategoryQueue(category));

  const pool = byCategory.get(category) || INSPIRE_ITEMS;
  const item = pool[Math.floor(Math.random() * pool.length)] || INSPIRE_ITEMS[0];
  return item.text;
}

